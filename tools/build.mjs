import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createHash } from 'node:crypto';

export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const firebasePattern = String.raw`^https:\/\/firebaseremoteconfig\.googleapis\.com\/v1\/projects\/locket-4252a\/namespaces\/[^/?]+:fetch(?:\?|$)`;
export const revenuecatPattern = String.raw`^https:\/\/api\.revenuecat\.com\/v1\/(?:receipts|subscribers\/[^/?]+)(?:\?|$)`;

export function validateSettings(settings) {
  if (!Number.isInteger(settings.videoSeconds) || settings.videoSeconds < 1 || settings.videoSeconds > 120) {
    throw new Error('videoSeconds must be an integer from 1 to 120. Device/server support is separate.');
  }
  const { owner, repository, ref } = settings.github || {};
  for (const [name, value] of Object.entries({ owner, repository, ref })) {
    if (typeof value !== 'string' || !/^[A-Za-z0-9][A-Za-z0-9_.-]*$/.test(value) || value.includes('..')) {
      throw new Error(`Invalid github.${name}; use a simple owner/repo/branch or commit SHA.`);
    }
  }
  return settings;
}

export function makeModule(base = '') {
  const script = name => base ? `${base}/scripts/${name}.js` : `scripts/${name}.js`;
  return [
    '#!name=Locket Zim',
    '#!desc=Own scripts: video configuration and filter UI diagnostics. AI/photobooth not yet verified.',
    '#!category=Locket Zim',
    '# Generated by tools/build.mjs. Edit settings.json and src/ instead.',
    '',
    '[Script]',
    `zim_revenuecat_request = type=http-request, pattern=${revenuecatPattern}, script-path=${script('revenuecat')}, timeout=10`,
    `zim_revenuecat_response = type=http-response, pattern=${revenuecatPattern}, script-path=${script('revenuecat')}, requires-body=true, max-size=0, timeout=10`,
    `zim_remote_config_request = type=http-request, pattern=${firebasePattern}, script-path=${script('remote-config')}, timeout=10`,
    `zim_remote_config_response = type=http-response, pattern=${firebasePattern}, script-path=${script('remote-config')}, requires-body=true, max-size=0, timeout=10`,
    '',
    '[MITM]',
    'hostname = %APPEND% api.revenuecat.com, firebaseremoteconfig.googleapis.com',
    ''
  ].join('\n');
}

export async function build(destination = root, suppliedSettings) {
  const settings = validateSettings(suppliedSettings || JSON.parse(await readFile(path.join(root, 'settings.json'), 'utf8')));
  const hostedBase = `https://raw.githubusercontent.com/${settings.github.owner}/${settings.github.repository}/${settings.github.ref}`;
  const config = JSON.stringify({ videoSeconds: settings.videoSeconds });
  const remoteSource = await readFile(path.join(root, 'src/remote-config.js'), 'utf8');
  const marker = '/* LOCKETZIM_CONFIG */ {}';
  if (remoteSource.split(marker).length !== 2) throw new Error('Expected exactly one Remote Config marker');
  const files = {
    'scripts/remote-config.js': remoteSource.replace(marker, config),
    'scripts/revenuecat.js': await readFile(path.join(root, 'src/revenuecat.js'), 'utf8'),
    'LocketZim.module': makeModule(hostedBase),
    'LocketZim.local.module': makeModule()
  };
  const manifest = { version: '3.0.0', videoSeconds: settings.videoSeconds, files: {} };
  for (const [name, content] of Object.entries(files)) {
    const target = path.join(destination, name);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, content);
    manifest.files[name] = { bytes: Buffer.byteLength(content), sha256: createHash('sha256').update(content).digest('hex') };
  }
  await writeFile(path.join(destination, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  return manifest;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const manifest = await build();
  console.log(`Built ${Object.keys(manifest.files).length} files for zim1st/locketzim; video target ${manifest.videoSeconds}s.`);
}
